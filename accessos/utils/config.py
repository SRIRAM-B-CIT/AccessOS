def _toml_value(val: Any) -> str:
    """Format a basic Python value for TOML."""
    if isinstance(val, bool):
        return "true" if val else "false"
    elif isinstance(val, (int, float)):
        return str(val)
    elif isinstance(val, str):
        escaped = val.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    elif isinstance(val, list):
        items = ", ".join(_toml_value(x) for x in val)
        return f"[{items}]"
    return f'"{val}"'


def dump_toml(data: dict) -> str:
    """Serialize a nested dictionary to standard TOML string."""
    lines: list[str] = [
        "# AccessOS User Configuration",
        "# Auto-generated by AccessOS Settings — edit with care",
        "",
    ]
    # Top-level primitives
    for k, v in data.items():
        if not isinstance(v, dict):
            lines.append(f"{k} = {_toml_value(v)}")

    # Sections
    for section, subdict in sorted(data.items()):
        if isinstance(subdict, dict):
            lines.append(f"\n[{section}]")
            for k, v in sorted(subdict.items()):
                lines.append(f"{k} = {_toml_value(v)}")

    return "\n".join(lines) + "\n"


class Config:
    """
    Layered configuration: built-in defaults ← TOML file on disk.

    The file is loaded at construction; call :meth:`save` to persist changes,
    or :meth:`restore_defaults` to reset to factory configuration.
    """

    def __init__(self, config_path: Path | None = None) -> None:
        self._data: dict = copy.deepcopy(_DEFAULTS)
        self._listeners: list[Callable[[str, Any], None]] = []

        if config_path is None:
            config_path = Path.home() / ".config" / "accessos" / "settings.toml"
        self.config_path = Path(config_path)
        self._load_from_file()

    # ── Internal helpers ───────────────────────────────────────────────────────

    @staticmethod
    def _deep_merge(base: dict, override: dict) -> None:
        """Recursively merge *override* into *base* (in-place)."""
        for key, value in override.items():
            if isinstance(value, dict) and isinstance(base.get(key), dict):
                Config._deep_merge(base[key], value)
            else:
                base[key] = copy.deepcopy(value)

    def _load_from_file(self) -> None:
        if not self.config_path.exists():
            log.debug("No config file at %s — using defaults", self.config_path)
            return
        try:
            with open(self.config_path, "rb") as fh:
                file_data = tomllib.load(fh)
            self._deep_merge(self._data, file_data)
            log.info("Config loaded from %s", self.config_path)
        except Exception as exc:
            log.warning("Config load failed (%s) — using defaults", exc)

    # ── Public API ─────────────────────────────────────────────────────────────

    def get(self, *keys: str, default: Any = None) -> Any:
        """
        Retrieve a value by dotted key path.

        Example::
            cfg.get("apps", "browser")          # ["firefox"]
            cfg.get("missing", default="nope")  # "nope"
        """
        node: Any = self._data
        for key in keys:
            if isinstance(node, dict):
                node = node.get(key, default)
            else:
                return default
        return node

    def set(self, *keys: str, value: Any) -> None:
        """
        Set a configuration value by key path.

        Example::
            cfg.set("theme", "font_size", value=22)
        """
        if not keys:
            raise ValueError("At least one key is required")

        node = self._data
        for key in keys[:-1]:
            if key not in node or not isinstance(node[key], dict):
                node[key] = {}
            node = node[key]

        last_key = keys[-1]
        node[last_key] = value
        self._notify_listeners(".".join(keys), value)

    def save(self) -> bool:
        """Persist current configuration to disk as TOML."""
        try:
            self.config_path.parent.mkdir(parents=True, exist_ok=True)
            toml_text = dump_toml(self._data)
            # Write atomically via temp file
            tmp_path = self.config_path.with_suffix(".tmp")
            tmp_path.write_text(toml_text, encoding="utf-8")
            tmp_path.replace(self.config_path)
            log.info("Saved configuration to %s", self.config_path)
            return True
        except Exception as exc:
            log.error("Failed to save config to %s: %s", self.config_path, exc)
            return False

    def restore_defaults(self) -> bool:
        """Reset configuration back to AccessOS factory defaults and save."""
        self._data = copy.deepcopy(_DEFAULTS)
        success = self.save()
        self._notify_listeners("all", self._data)
        log.info("Restored configuration to AccessOS defaults")
        return success

    def reload(self) -> None:
        """Re-read the config file from disk."""
        self._data = copy.deepcopy(_DEFAULTS)
        self._load_from_file()
        self._notify_listeners("all", self._data)

    def add_change_listener(self, callback: Callable[[str, Any], None]) -> None:
        """Register a callback function when any setting changes."""
        if callback not in self._listeners:
            self._listeners.append(callback)

    def _notify_listeners(self, key_path: str, value: Any) -> None:
        for cb in self._listeners:
            try:
                cb(key_path, value)
            except Exception as exc:
                log.warning("Config change listener failed: %s", exc)
